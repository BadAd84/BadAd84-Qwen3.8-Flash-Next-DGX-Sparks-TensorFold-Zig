#!/usr/bin/env python3
"""compile_batch.py: every PR text of the October 2026 batch (the part of each package's PR.md after its `---` line:
the title and body exactly as posted) in upload order, into BATCH-2026-10-TEXTS.md. Fails when a text still holds a
placeholder ([[...]]) or a package lacks pr.diff / PR.md / mutants.sh."""
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
ORDER = [
    ("Qwen3.8 Flash Next recipe, Zig release 1.0.0 (2026-10-08 batch)", [
        "zig-pr-confidence", "zig-pr-argmax", "zig-pr-mtp-fp8"]),
    ("Qwen3.8 Flash Next recipe, Zig speed batch 2", [
        "zig-pr-ngram-host", "zig-pr-copy-window", "zig-pr-copy-resync", "zig-pr-copy-shared", "zig-pr-seq-pool",
        "zig-pr-batch-draws", "zig-pr-fp8-fused-head-mt", "zig-pr-decode-glue", "zig-pr-draft-stop-lines"]),
    ("Qwen3.8 Flash Next recipe, Zig speed batch 3", [
        "zig-pr-fill-fix", "zig-pr-readout-12bit", "zig-pr-indexer-select", "zig-pr-prompt-tiles",
        "zig-pr-prefill-rows"]),
    ("Qwen3.8 Flash Next recipe (PARKED: the recipe moved to the Zig engine; not posted)", [
        "qwen-pr-copy-first", "qwen-pr-ple-page-cache", "qwen-pr-ple-native", "qwen-pr-chain-stop",
        "qwen-pr-mtp-graphs", "qwen-pr-ple-defer", "qwen-pr-tokenize-nogil"]),
]


def main():
    out, problems, n = ["# October 2026 upstream batch: every PR text (parked, not posted)", "",
                        "Generated by `upstream/compile_batch.py` from each package's `PR.md` (the part after its `---`"
                        " line). Upload order; patch numbers are placeholders the maintainers renumber.", ""], [], 0
    for repo, dirs in ORDER:
        out += [f"# {repo}", ""]
        for d in dirs:
            p = HERE / d
            for f in ("pr.diff", "PR.md", "mutants.sh"):
                if not (p / f).is_file():
                    problems.append(f"{d}: no {f}")
            if not (p / "PR.md").is_file():
                continue
            text = (p / "PR.md").read_text(encoding="utf-8")
            parts = re.split(r"(?m)^---\s*$", text, maxsplit=1)
            if len(parts) != 2:
                problems.append(f"{d}: no --- line in PR.md")
                continue
            body = parts[1].strip()
            for m in re.finditer(r"\[\[[^\]]*\]\]", body):
                problems.append(f"{d}: placeholder {m.group(0)[:80]}")
            n += 1
            out += [f"## {n}. `{d}`", "", body, "", "---", ""]
    (HERE / "BATCH-2026-10-TEXTS.md").write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"{n} texts -> BATCH-2026-10-TEXTS.md")
    for p in problems:
        print("PROBLEM", p)
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    main()
